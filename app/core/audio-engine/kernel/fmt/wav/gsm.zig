//!     镜像 FFmpeg gsmdec.c 仅告警不拒绝）。
//!
//! 算法与常量表重构自 FFmpeg `libavcodec/gsmdec_template.c` / `gsmdec_data.c` /
//! `msgsmdec.c` / `gsmdec.c`（reference/FFmpeg，参考实现非直接复制）。

