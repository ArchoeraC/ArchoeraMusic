/// 定长乘加（镜像 FFmpeg gsm_mult：(int)(a*b + 2^14) >> 15）。
/// 中间量按 u32 回绕，最终在**有符号**值上算术右移（符号位扩展），
/// 与 C 的 `(int)(...) >> 15` 语义一致；逻辑右移会在此处产生分歧。
fn gsmMult(a: i32, b: i32) i32 {
    const sum: u32 = @as(u32, @bitCast(a *% b)) +% (1 << 14);
    const s: i32 = @bitCast(sum);
    return s >> 15;
}

/// 对数面积解码（镜像 decode_log_area）
fn decodeLogArea(coded: i32, factor: i32, offset: i32) i32 {
    return gsmMult((coded << 10) - offset, factor) * 2;
}

/// 反射系数 → 反射因子（镜像 get_rrp）
fn getRrp(filtered: i32) i32 {
    var abs: i32 = if (filtered < 0) -filtered else filtered;
    if (abs < 11059) {
        abs <<= 1;
    } else if (abs < 20070) {
        abs += 11059;
    } else {
        abs = (abs >> 2) + 26112;
    }
    return if (filtered < 0) -abs else abs;
}

/// 短时合成滤波（镜像 filter_value，v 为跨调用保持状态）
fn filterValue(in0: i32, rrp: *const [8]i32, v: *[9]i32) i32 {
    var in_v = in0;
    var i: usize = 8;
    while (i > 0) {
        i -= 1;
        in_v -= gsmMult(rrp[i], v[i]);
        v[i + 1] = v[i] + gsmMult(rrp[i], in_v);
    }
    v[0] = in_v;
    return in_v;
}

/// 长时预测合成（镜像 long_term_synth；`dst_off` 为 ref_buf 内子帧起点）
fn longTermSynth(ctx: *Context, dst_off: usize, lag: usize, gain_idx: usize) void {
    const gain: i32 = long_term_gain[gain_idx];
    for (0..40) |i| {
        const v = gsmMult(gain, ctx.ref_buf[dst_off + i - lag]);
        ctx.ref_buf[dst_off + i] = @as(i16, @truncate(v));
    }
}

/// apcm 去量化累加（镜像 apcm_dequant_add；`dst_off` 为 ref_buf 内目标起点）
fn apcmDequantAdd(ctx: *Context, dst_off: usize, gb: *BitReader, frame_bits: *const [13]u8) Error!void {
    const maxidx = try gb.read(6);
    const tab = dequant[maxidx];
    for (0..13) |i| {
        const val = try gb.read(frame_bits[i]);
        const v = @as(i32, ctx.ref_buf[dst_off + 3 * i]) + @as(i32, tab[requant[frame_bits[i]][val]]);
        ctx.ref_buf[dst_off + 3 * i] = @as(i16, @truncate(v));
    }
}

fn clip16(v: i32) i32 {
    return std.math.clamp(v, -32768, 32767);
}

/// 短时合成（镜像 short_term_synth；每帧调用一次，末尾翻转 lar_idx）
fn shortTermSynth(ctx: *Context, dst: []i16, src: []const i16) void {
    const li: usize = ctx.lar_idx;
    const lar = ctx.lar[li];
    const lar_prev = ctx.lar[li ^ 1];
    var rrp: [8]i32 = undefined;

    var i: usize = 0;
    while (i < 8) : (i += 1)
        rrp[i] = getRrp((lar_prev[i] >> 2) + (lar_prev[i] >> 1) + (lar[i] >> 2));
    i = 0;
    while (i < 13) : (i += 1)
        dst[i] = @as(i16, @truncate(filterValue(src[i], &rrp, &ctx.v)));

    i = 0;
    while (i < 8) : (i += 1)
        rrp[i] = getRrp((lar_prev[i] >> 1) + (lar[i] >> 1));
    i = 13;
    while (i < 27) : (i += 1)
        dst[i] = @as(i16, @truncate(filterValue(src[i], &rrp, &ctx.v)));

    i = 0;
    while (i < 8) : (i += 1)
        rrp[i] = getRrp((lar_prev[i] >> 2) + (lar[i] >> 1) + (lar[i] >> 2));
    i = 27;
    while (i < 40) : (i += 1)
        dst[i] = @as(i16, @truncate(filterValue(src[i], &rrp, &ctx.v)));

    i = 0;
    while (i < 8) : (i += 1)
        rrp[i] = getRrp(lar[i]);
    i = 40;
    while (i < 160) : (i += 1)
        dst[i] = @as(i16, @truncate(filterValue(src[i], &rrp, &ctx.v)));

    ctx.lar_idx ^= 1;
}

/// 后处理（镜像 postprocess：低通 + 去低 3 位）
fn postprocess(data: []i16, msr0: i32) i32 {
    var msr = msr0;
    for (data) |*d| {
        msr = clip16(@as(i32, d.*) + gsmMult(msr, 28180));
        d.* = @intCast(clip16(msr * 2) & ~@as(i32, 7));
    }
    return msr;
}

