/// 解码一个 GSM 帧（160 样本）。`mode` 为码率模式 0..8（GSM_MS 缩减用；纯 GSM 恒 0）。
/// `samples` 容量须 >= frame_size。
fn gsmDecodeBlock(ctx: *Context, samples: []i16, gb: *BitReader, mode: usize) Error!void {
    const lar = &ctx.lar[ctx.lar_idx];
    lar[0] = decodeLogArea(@intCast(try gb.read(6)), 13107, 1 << 15);
    lar[1] = decodeLogArea(@intCast(try gb.read(6)), 13107, 1 << 15);
    lar[2] = decodeLogArea(@intCast(try gb.read(5)), 13107, (1 << 14) + 2048 * 2);
    lar[3] = decodeLogArea(@intCast(try gb.read(5)), 13107, (1 << 14) - 2560 * 2);
    lar[4] = decodeLogArea(@intCast(try gb.read(4)), 19223, (1 << 13) + 94 * 2);
    lar[5] = decodeLogArea(@intCast(try gb.read(4)), 17476, (1 << 13) - 1792 * 2);
    lar[6] = decodeLogArea(@intCast(try gb.read(3)), 31454, (1 << 12) - 341 * 2);
    lar[7] = decodeLogArea(@intCast(try gb.read(3)), 29708, (1 << 12) - 1144 * 2);

    var base: usize = 120;
    for (0..4) |sf| {
        const lag_raw: i32 = @intCast(try gb.read(7));
        const gain_idx = try gb.read(2);
        const offset = try gb.read(2);
        const lag: usize = @intCast(std.math.clamp(lag_raw, 40, 120));
        longTermSynth(ctx, base, lag, gain_idx);
        try apcmDequantAdd(ctx, base + offset, gb, &apcm_bits_tab[apcm_mode[mode][sf]]);
        base += 40;
    }
    // 当前帧尾部 120 样本滚入 ref_buf 前段（供下一帧 lag 回溯）
    @memcpy(ctx.ref_buf[0..120], ctx.ref_buf[160..280]);
    shortTermSynth(ctx, samples, ctx.ref_buf[120..280]);
    ctx.msr = postprocess(samples, ctx.msr);
}

/// 解码 GSM_MS 块（WAV tag 0x31/0x32/0x1500）。
/// `in` 为整块（41..65 字节，步进 3）；`out` 容量须 >= ms_frame_size（交错 s16）。
pub fn decodeGsmMs(ctx: *Context, in: []const u8, out: []i16) Error!void {
    // 块长校验镜像 FFmpeg gsm_init：41 ≤ align ≤ 65 且 (align-41) % 3 == 0
    if (in.len < msn_min_block_size or in.len > ms_block_size or
        (in.len - msn_min_block_size) % 3 != 0)
    {
        return error.Corrupt;
    }
    const mode: usize = (ms_block_size - in.len) / 3;
    var gb = BitReader{ .buf = in, .bit_pos = 0, .lsb_first = true };
    try gsmDecodeBlock(ctx, out[0..frame_size], &gb, mode);
    try gsmDecodeBlock(ctx, out[frame_size..], &gb, mode);
}

/// 解码纯 GSM 帧（AIFF-C "GSM "）。
/// `in` 为整块（≥ 33 字节，仅消费 260 bit）；`out` 容量须 >= frame_size（交错 s16）。
pub fn decodeGsm(ctx: *Context, in: []const u8, out: []i16) Error!void {
    if (in.len < block_size) return error.Corrupt;
    var gb = BitReader{ .buf = in, .bit_pos = 0, .lsb_first = false };
    _ = try gb.read(4); // 帧首 GSM 魔数 0xD（缺失仅忽略，镜像 FFmpeg 仅告警不拒绝）
    try gsmDecodeBlock(ctx, out[0..frame_size], &gb, 0);
}

