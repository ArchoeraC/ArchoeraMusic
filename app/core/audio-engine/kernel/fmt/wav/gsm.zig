test "gsm: 位读取器 LSB/MSB 位序" {
    // 0x8C = 1000 1100（bit7..0 = 1,0,0,0,1,1,0,0）：
    //   MSB（get_bits）：首读 bit 为结果最高位 → bit7..4 = 1000 = 8；bit3..0 = 1100 = 12；
