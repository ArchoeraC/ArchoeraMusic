    var msb = BitReader{ .buf = &[_]u8{0x8C}, .bit_pos = 0, .lsb_first = false };
    try testing.expectEqual(@as(u32, 8), try msb.read(4));
    try testing.expectEqual(@as(u32, 12), try msb.read(4));
    var lsb = BitReader{ .buf = &[_]u8{0x8C}, .bit_pos = 0, .lsb_first = true };
